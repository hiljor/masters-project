def map_display_title(dataset_name: str) -> str:
    """Returns a display title with metadata for a dataset name.

    Looks up `dataset_name` (e.g. "horse_dots.txt") in MAP_METADATA and
    returns a string like "Dots (n=224, m=408, min k=3)". If the dataset
    is not found in MAP_METADATA (e.g. it is a generated size_test graph,
    or an unknown file), the raw dataset_name is returned unchanged.

    Args:
        dataset_name: The map's file name, as recorded in the results CSV
            'Dataset' column (e.g. "horse_dots.txt").

    Returns:
        A human-friendly title string, or dataset_name if no metadata is
        available for it.
    """
    meta = MAP_METADATA.get(dataset_name)
    if meta is None:
        return dataset_name
    return (
        f"{meta['title']} (n={meta['n_nodes']}, m={meta['m_edges']}, "
        f"min k={meta['min_k']})"
    )


