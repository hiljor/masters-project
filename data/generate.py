def generate_size_test(size):
  mid = size // 2
  cols = [mid, mid + 2, mid - 2]
  rows = [mid]
  level_map = [["#" for _ in range(size)] for _ in range(size)]
  for i in range(size):
    for j in range(size):
      # clear the entire column or row marked for clearing
      if i in rows or j in cols:
        level_map[i][j] = " "
  # add horse
  level_map[mid][mid] = "H"
  
  # convert to list of strings
  level_map = ["".join(row) for row in level_map]
  return level_map


def _compute_map_metadata() -> dict:
    """Recomputes MAP_METADATA's n_nodes/m_edges/min_k values from the
    actual map files in the data directory, by loading each graph and
    running a minimum s-t separator computation.

    This is used by the `python data/generate.py` self-check below to
    verify that MAP_METADATA stays in sync with the map files; it is not
    used at benchmark/visualisation runtime (MAP_METADATA is a static
    dict so results stay stable and fast to import).

    Returns:
        A dict keyed by map file name with freshly computed
        {"n_nodes", "m_edges", "min_k"} values.
    """
    import sys

    repo_root = Path(__file__).resolve().parent.parent
    sys.path.insert(0, str(repo_root / "src"))

    from horse_algos.tools.map_loader import load_graph_from_map
    from horse_algos.graph import minSeparator

    computed = {}
    for filename in MAP_METADATA:
        graph, s, t = load_graph_from_map(filename)
        n_nodes = len(graph.nodeValues)
        m_edges = sum(len(adj) for adj in graph.adjList) // 2
        min_k = len(minSeparator(graph, s, t))
        computed[filename] = {
            "n_nodes": n_nodes,
            "m_edges": m_edges,
            "min_k": min_k,
        }
    return computed


if __name__ == "__main__":
    # Recompute the graph metadata directly from the map files and report
    # any mismatch against the static MAP_METADATA table above, so the
    # table can be manually verified/updated after editing a map file.
    computed = _compute_map_metadata()
    mismatches = []
    for filename, meta in MAP_METADATA.items():
        fresh = computed[filename]
        for key in ("n_nodes", "m_edges", "min_k"):
            if meta[key] != fresh[key]:
                mismatches.append((filename, key, meta[key], fresh[key]))
        print(
            f"{filename}: title={meta['title']!r} n_nodes={fresh['n_nodes']} "
            f"m_edges={fresh['m_edges']} min_k={fresh['min_k']}"
        )

    if mismatches:
        print("\nMismatches between MAP_METADATA and freshly computed values:")
        for filename, key, old, new in mismatches:
            print(f"  {filename}: {key} recorded={old} computed={new}")
    else:
        print("\nMAP_METADATA is up to date with the current map files.")
